defmodule Zifiri.E2ETest do
  @moduledoc """
  Integration checks against a *running* server, over real HTTP.

  These are the three facts `scripts/e2e/run.sh` proves with a browser, minus
  the browser: the server is up, `/` serves the client shell, and `/api/pow` is
  bound and answering. They live behind `@tag :integration` and are excluded by
  `test/test_helper.exs`, so `mix test` stays hermetic; run them with

      mix test --include integration test/e2e_test.exs

  The base URL comes from `ZIFIRI_E2E_BASE` (default `http://127.0.0.1:4000`).
  Nothing here is skipped: if the server is not running the test fails and says
  so, because a skipped E2E is indistinguishable from a passing one in a CI
  summary.

  ## What a 404 on `/api/pow` would mean

  `GET /api/pow` refuses a request that carries no owner token with a `400` and
  the constant body `{"error":"refused"}`. A `404` would be a different answer:
  it is the router saying no such route is bound, which is the regression this
  test exists to catch. The two are asserted apart by status and by body.
  """

  use ExUnit.Case, async: false

  @moduletag :integration

  # `Zifiri.Router.reply/3` pads every API answer to this size. The constant is
  # restated here on purpose: a change to it is a change to the fingerprint the
  # API presents, and this test should fail when that happens.
  @response_bytes 16_384

  @base System.get_env("ZIFIRI_E2E_BASE", "http://127.0.0.1:4000")

  test "the server is up and answers /health" do
    {status, _headers, body} = get("/health")

    assert status == 200,
           "GET #{@base}/health answered #{status}. Is the server running? " <>
             "Start it with `ZIFIRI_E2E_PORT=4000 mix run --no-start scripts/e2e/serve.exs` " <>
             "(or `mix phx.server`)."

    assert body == ~s({"status":"ok"}),
           "GET #{@base}/health answered something else — port #{port()} is not zifiri: #{inspect(body)}"
  end

  test "GET / serves the client shell" do
    {status, headers, body} = get("/")

    assert status == 200, "GET #{@base}/ expected 200, got #{status}"

    assert content_type(headers) =~ "text/html",
           "GET #{@base}/ is not HTML (#{inspect(content_type(headers))}) — Plug.Static is not serving priv/static"

    # The build output is gitignored and generated by `make static`. An empty or
    # zeroed `priv/static/index.html` is served as a 200 with a body that is not
    # HTML, which is how this check earns its keep.
    assert byte_size(body) > 500,
           "GET #{@base}/ returned #{byte_size(body)} bytes — priv/static/index.html looks truncated or empty"

    assert String.starts_with?(body, "<!doctype html>"),
           "GET #{@base}/ does not start with a doctype: #{inspect(binary_part(body, 0, 40))}"

    assert body =~ ~s(id="app"),
           "the shell has no #app mount point"

    assert body =~ "/assets/index-",
           "the shell does not reference a built bundle — `make static` did not copy client/dist"
  end

  test "GET /api/pow is bound and refuses a request with no owner token" do
    {status, headers, body} = get("/api/pow")

    # 404 here is the router saying the route is gone; 400 is the route saying
    # it will not issue a challenge without a capability. Only one of those is
    # a pass.
    refute status == 404,
           "GET #{@base}/api/pow answered 404 — the route is not bound at all. " <>
             "Body: #{inspect(binary_part(body, 0, 40))}"

    assert status == 400,
           "GET #{@base}/api/pow expected 400 (refused), got #{status}"

    assert String.starts_with?(body, ~s({"error":"refused"})),
           "GET #{@base}/api/pow body is not the constant refusal: #{inspect(binary_part(body, 0, 80))}"

    assert byte_size(body) == @response_bytes,
           "GET #{@base}/api/pow answered #{byte_size(body)} bytes, expected the fixed #{@response_bytes}"

    assert content_type(headers) =~ "application/json",
           "GET #{@base}/api/pow is not JSON (#{inspect(content_type(headers))})"
  end

  test "the demo fixtures chunk is served, so ?demo=1 has something to import" do
    # `?demo=1` is `import("./fixtures")`: a missing chunk would leave the badge
    # and both lists empty with no server-side error to point at.
    [fixture | _] = Path.wildcard("priv/static/assets/fixtures-*.js")
    path = "/assets/" <> Path.basename(fixture)

    {status, _headers, body} = get(path)

    assert status == 200, "GET #{@base}#{path} expected 200, got #{status}"
    assert byte_size(body) > 0, "GET #{@base}#{path} returned an empty chunk"
  end

  # -- helpers ---------------------------------------------------------------

  defp port, do: URI.parse(@base).port

  # One GET over `:gen_tcp`, not `:httpc`.
  #
  # `:httpc` would be shorter, but `:inets` on this toolchain fails to load
  # `:http_util` ("function :http_util.timestamp/0 is undefined"), and a test
  # that cannot make a request proves nothing. `:gen_tcp` is in `:kernel` and
  # always present. `Connection: close` means the body ends at EOF, so there is
  # no read-until-length logic to get wrong.
  defp get(path) do
    uri = URI.parse(@base <> path)
    host = uri.host
    port = uri.port

    case :gen_tcp.connect(
           String.to_charlist(host),
           port,
           [:binary, packet: :raw, active: false],
           2_000
         ) do
      {:ok, socket} ->
        request = [
          "GET ",
          path,
          " HTTP/1.1\r\n",
          "Host: ",
          host,
          ":",
          Integer.to_string(port),
          "\r\n",
          "Connection: close\r\n\r\n"
        ]

        :ok = :gen_tcp.send(socket, request)
        raw = recv_all(socket, [])
        :gen_tcp.close(socket)
        parse(raw)

      {:error, reason} ->
        flunk(
          "GET #{@base}#{path} could not connect: #{inspect(reason)}. " <>
            "The integration server is not running on #{@base}; start it with " <>
            "`ZIFIRI_E2E_PORT=#{port} mix run --no-start scripts/e2e/serve.exs`."
        )
    end
  end

  defp recv_all(socket, acc) do
    case :gen_tcp.recv(socket, 0, 5_000) do
      {:ok, data} -> recv_all(socket, [acc, data])
      {:error, :closed} -> IO.iodata_to_binary(acc)
      {:error, reason} -> flunk("the connection broke mid-response: #{inspect(reason)}")
    end
  end

  defp parse(raw) do
    [head, body] = :binary.split(raw, "\r\n\r\n")
    [status_line | header_lines] = String.split(head, "\r\n")
    [_version, status | _] = String.split(status_line, " ")

    headers =
      Map.new(header_lines, fn line ->
        [name, value] = String.split(line, ":", parts: 2)
        {String.downcase(name), String.trim(value)}
      end)

    {String.to_integer(status), headers, decode_body(headers, body)}
  end

  # Bandit answers a fixed-length body with `content-length`; a chunked answer
  # is decoded rather than compared as if the framing were content.
  defp decode_body(%{"transfer-encoding" => "chunked"}, body), do: dechunk(body, [])
  defp decode_body(_headers, body), do: body

  defp dechunk(body, acc) do
    case :binary.split(body, "\r\n") do
      [size_line, rest] ->
        size = size_line |> String.split(";") |> hd() |> String.trim() |> String.to_integer(16)

        if size == 0 do
          IO.iodata_to_binary(acc)
        else
          <<chunk::binary-size(^size), "\r\n", tail::binary>> = rest
          dechunk(tail, [acc, chunk])
        end

      _ ->
        IO.iodata_to_binary(acc)
    end
  end

  defp content_type(headers), do: Map.get(headers, "content-type", "")
end
